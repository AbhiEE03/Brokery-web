const { normalizeIndianMobile } = require("../utils/phone");

describe("normalizeIndianMobile", () => {
	test.each([
		["9876543210", "+919876543210"],
		["98765 43210", "+919876543210"],
		["98765-43210", "+919876543210"],
		["987.654.3210", "+919876543210"],
		["(98765) 43210", "+919876543210"],
		["09876543210", "+919876543210"],
		["919876543210", "+919876543210"],
		["+919876543210", "+919876543210"],
		["+91 98765 43210", "+919876543210"],
		["+91-98765-43210", "+919876543210"],
		["  +91 9876543210  ", "+919876543210"],
		["6000000000", "+916000000000"],
		["7012345678", "+917012345678"],
		["8123456789", "+918123456789"],
		[9876543210, "+919876543210"],
	])("%p → %p", (input, expected) => {
		expect(normalizeIndianMobile(input)).toBe(expected);
	});

	test.each([
		["5876543210", "starts with 5"],
		["987654321", "9 digits"],
		["98765432101", "11 digits without a leading 0"],
		["+1 9876543210", "another country code"],
		["+44 7911 123456", "UK number"],
		["98765abc10", "letters"],
		["", "empty"],
		[null, "null"],
		["0098765432100", "too long"],
		["0112345678", "Delhi landline"],
	])("%p is rejected (%s)", (input) => {
		expect(normalizeIndianMobile(input)).toBeNull();
	});
});
